/* Service worker: מנווט יתר לחץ דם (PWA)
   Generated by build_pwa.py. VERSION changes whenever index.html, the manifest or the icons change,
   which makes the browser install the new version on the next launch. */
'use strict';
const VERSION = 'bb4ecb946c1d';
const APP_CACHE = 'htn-app-' + VERSION;
const FONT_CACHE = 'htn-fonts-v1';
const PRECACHE = ["./index.html", "./manifest.webmanifest", "./apple-touch-icon.png", "./favicon-32.png", "./favicon.svg", "./icon-192.png", "./icon-512.png", "./maskable-192.png", "./maskable-512.png"];
const FONT_CSS = ["https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Hebrew:wght@400;500;600;700&family=IBM+Plex+Mono:wght@500;600&display=swap"];
const FONT_SUBSETS = ['hebrew', 'latin'];

const scopePath = () => new URL(self.registration.scope).pathname;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(APP_CACHE);
    await cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })));
    // Fonts are a nicety: never let them block or fail the install.
    await Promise.race([warmFonts().catch(() => {}), new Promise((r) => setTimeout(r, 8000))]);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith('htn-app-') && k !== APP_CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // The app page itself: served from cache, so it opens instantly and offline.
  if (req.mode === 'navigate' && url.origin === self.location.origin) {
    const root = scopePath();
    if (url.pathname === root || url.pathname === root + 'index.html') {
      event.respondWith(appShell(event));
    }
    return;
  }

  // The app's own files (manifest, icons): cache first.
  if (url.origin === self.location.origin) {
    event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
    return;
  }

  // Google Fonts: stylesheet stale-while-revalidate, font files cache-first.
  if (url.hostname === 'fonts.googleapis.com') {
    event.respondWith(staleWhileRevalidate(req));
    return;
  }
  if (url.hostname === 'fonts.gstatic.com') {
    event.respondWith(cacheFirst(req));
  }
});

// Pages that were opened from an older copy while a newer index.html was being saved.
const staleClients = new Set();

// The page asks after launch (and when resumed) whether index.html on the server changed.
// This also catches an update where only index.html was replaced and sw.js stayed the same.
self.addEventListener('message', (event) => {
  if (!event.data || event.data.type !== 'check-update') return;
  const src = event.source;
  event.waitUntil((async () => {
    let changed = !!(src && staleClients.has(src.id));
    if (!changed) changed = await checkIndex().catch(() => false);
    if (changed && src) src.postMessage({ type: 'app-updated' });
  })());
});

async function checkIndex() {
  const cache = await caches.open(APP_CACHE);
  const res = await fetch('./index.html', { cache: 'no-cache' });
  if (!res.ok) return false;
  const hit = await cache.match('./index.html');
  const fresh = await res.clone().text();
  const old = hit ? await hit.text() : '';
  if (fresh.length < 2000 || fresh === old) return false;
  await cache.put('./index.html', res);
  return true;
}

// Serve the saved copy at once (works offline), and look for a newer one in the background.
async function appShell(event) {
  const cache = await caches.open(APP_CACHE);
  const hit = await cache.match('./index.html');
  if (hit) {
    const clientId = event.resultingClientId;
    event.waitUntil(checkIndex().then(async (changed) => {
      if (!changed || !clientId) return;
      staleClients.add(clientId);
      const client = await self.clients.get(clientId);
      if (client) client.postMessage({ type: 'app-updated' });
    }).catch(() => {}));
    return hit;
  }
  try {
    return await fetch(event.request);
  } catch (e) {
    return new Response('<!doctype html><meta charset="utf-8"><p dir="rtl" style="font:16px sans-serif;padding:24px">אין חיבור לרשת והאפליקציה עוד לא נשמרה במכשיר. פתחו אותה פעם אחת עם אינטרנט.</p>',
      { headers: { 'Content-Type': 'text/html; charset=utf-8' } });
  }
}

async function staleWhileRevalidate(req) {
  const cache = await caches.open(FONT_CACHE);
  const hit = await cache.match(req);
  const net = fetch(req).then((res) => {
    if (res && (res.ok || res.type === 'opaque')) cache.put(req, res.clone());
    return res;
  }).catch(() => null);
  return hit || (await net) || new Response('', { status: 504 });
}

async function cacheFirst(req) {
  const cache = await caches.open(FONT_CACHE);
  const hit = await cache.match(req);
  if (hit) return hit;
  try {
    const res = await fetch(req);
    if (res && (res.ok || res.type === 'opaque')) cache.put(req, res.clone());
    return res;
  } catch (e) {
    return new Response('', { status: 504 });
  }
}

// Save the Hebrew and Latin font files during install, so the first offline launch keeps the design.
async function warmFonts() {
  const cache = await caches.open(FONT_CACHE);
  for (const cssUrl of FONT_CSS) {
    const res = await fetch(cssUrl, { mode: 'cors', credentials: 'omit' });
    if (!res.ok) continue;
    await cache.put(cssUrl, res.clone());
    const css = await res.text();
    const urls = [];
    for (const block of css.split('/* ').slice(1)) {
      const subset = block.slice(0, block.indexOf(' */')).trim();
      if (!FONT_SUBSETS.includes(subset)) continue;
      const m = block.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)\s]+)\)/);
      if (m) urls.push(m[1]);
    }
    await Promise.all(urls.map(async (u) => {
      if (await cache.match(u)) return;
      const r = await fetch(u, { mode: 'cors', credentials: 'omit' });
      if (r.ok) await cache.put(u, r);
    }));
  }
}
